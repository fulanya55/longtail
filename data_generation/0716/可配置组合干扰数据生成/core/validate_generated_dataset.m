function validate_generated_dataset(bundle, cfg, registry, schema, scenario)
%VALIDATE_GENERATED_DATASET 对已生成数据集执行结构与语义一致性校验。
%   VALIDATE_GENERATED_DATASET(BUNDLE, CFG, REGISTRY, SCHEMA, SCENARIO)
%   检查波形、标签、参数 mask、manifest 所有权、known/unknown、样本种子、
%   功率标定、旧格式矩阵和场景标志。SCENARIO 取 balanced、imbalanced 或
%   openset。校验成功不返回值；失败使用稳定的 JammingDataset:* 标识。

    scenario = normalize_scenario(scenario);
    requiredFields = {'iq_complex', 'label_all', 'label_selected', ...
        'known_label', 'unknown_present', 'unknown_component_count', ...
        'parameter_values', 'parameter_mask', ...
        'component_power_offset_dB', 'component_target_power_dB', ...
        'component_measured_power_dB', 'relative_power_dB', ...
        'weak_component_mask', 'component_nominal_JNR_dB', ...
        'component_effective_JNR_dB', 'component_nominal_amplitude', ...
        'component_effective_amplitude', 'component_seeds', ...
        'receiver_noise_seed', 'target_present', 'target_delay_s', ...
        'target_range_m', 'target_target_power_dB', ...
        'target_measured_power_dB', 'manifest', 'metadata'};
    if ~isstruct(bundle) || ~isscalar(bundle) || ...
            ~all(isfield(bundle, requiredFields)) || ~istable(bundle.manifest)
        error('JammingDataset:InvalidStructure', ...
            'bundle 缺少必需字段或 manifest 不是 table。');
    end

    sampleCount = height(bundle.manifest);
    parameterCount = height(schema);
    registryCodes = {registry.code};
    enabledMask = ismember(registryCodes, cfg.types.enabled);
    knownMask = ismember(registryCodes, cfg.types.known);
    expectedWaveformSize = [sampleCount, cfg.derived.sample_length];
    if ~isequal(size(bundle.iq_complex), expectedWaveformSize) || ...
            ~all(isfinite(real(bundle.iq_complex)), 'all') || ...
            ~all(isfinite(imag(bundle.iq_complex)), 'all')
        error('JammingDataset:InvalidWaveform', ...
            'iq_complex 的形状或有限性不符合配置。');
    end
    require_binary_matrix(bundle.label_all, [sampleCount, numel(registry)], ...
        'label_all');
    require_binary_matrix(bundle.label_selected, ...
        [sampleCount, nnz(enabledMask)], 'label_selected');
    require_binary_matrix(bundle.known_label, ...
        [sampleCount, nnz(knownMask)], 'known_label');
    require_binary_matrix(bundle.parameter_mask, ...
        [sampleCount, parameterCount], 'parameter_mask');
    if ~isequal(size(bundle.parameter_values), ...
            [sampleCount, parameterCount]) || ...
            ~all(isfinite(bundle.parameter_values(bundle.parameter_mask))) || ...
            ~all(isnan(bundle.parameter_values(~bundle.parameter_mask)))
        error('JammingDataset:InvalidParameterTargets', ...
            'parameter_values 与 parameter_mask 的形状或 NaN 语义不一致。');
    end
    if numel(unique(bundle.manifest.sample_seed)) ~= sampleCount || ...
            numel(unique(bundle.receiver_noise_seed)) ~= sampleCount
        error('JammingDataset:DuplicateSeed', ...
            'sample_seed 和 receiver_noise_seed 必须逐样本唯一。');
    end

    variableFields = {'component_power_offset_dB', ...
        'component_target_power_dB', 'component_measured_power_dB', ...
        'relative_power_dB', 'weak_component_mask', ...
        'component_nominal_JNR_dB', 'component_effective_JNR_dB', ...
        'component_nominal_amplitude', 'component_effective_amplitude', ...
        'component_seeds'};
    for fieldIndex = 1:numel(variableFields)
        fieldName = variableFields{fieldIndex};
        if ~iscell(bundle.(fieldName)) || ...
                ~isequal(size(bundle.(fieldName)), [sampleCount, 1])
            error('JammingDataset:InvalidStructure', ...
                '%s 必须是 N×1 单元数组。', fieldName);
        end
    end
    columnFields = {'unknown_present', 'unknown_component_count', ...
        'receiver_noise_seed', 'target_present', 'target_delay_s', ...
        'target_range_m', 'target_target_power_dB', ...
        'target_measured_power_dB'};
    for fieldIndex = 1:numel(columnFields)
        fieldName = columnFields{fieldIndex};
        if ~isequal(size(bundle.(fieldName)), [sampleCount, 1])
            error('JammingDataset:InvalidStructure', ...
                '%s 必须是 N×1 逐样本列向量。', fieldName);
        end
    end
    require_binary_matrix(bundle.unknown_present, [sampleCount, 1], ...
        'unknown_present');
    require_binary_matrix(bundle.target_present, [sampleCount, 1], ...
        'target_present');
    if ~isnumeric(bundle.unknown_component_count) || ...
            any(~isfinite(bundle.unknown_component_count)) || ...
            any(bundle.unknown_component_count < 0) || ...
            any(bundle.unknown_component_count ~= ...
            floor(bundle.unknown_component_count)) || ...
            ~isnumeric(bundle.receiver_noise_seed) || ...
            any(~isfinite(bundle.receiver_noise_seed)) || ...
            any(bundle.receiver_noise_seed < 0) || ...
            any(bundle.receiver_noise_seed ~= floor(bundle.receiver_noise_seed))
        error('JammingDataset:InvalidStructure', ...
            'unknown_component_count 和 receiver_noise_seed 必须是有限非负整数。');
    end
    targetPresent = logical(bundle.target_present);
    targetNumericFields = {'target_delay_s', 'target_range_m', ...
        'target_target_power_dB', 'target_measured_power_dB'};
    for fieldIndex = 1:numel(targetNumericFields)
        fieldName = targetNumericFields{fieldIndex};
        values = bundle.(fieldName);
        if ~isnumeric(values) || ~isreal(values) || ...
                any(~isfinite(values(targetPresent))) || ...
                any(~isnan(values(~targetPresent)))
            error('JammingDataset:InvalidStructure', ...
                '%s 必须在目标存在时有限、目标不存在时为 NaN。', fieldName);
        end
    end
    if ~isfield(cfg.output, 'power_tolerance_dB') || ...
            ~isnumeric(cfg.output.power_tolerance_dB) || ...
            ~isreal(cfg.output.power_tolerance_dB) || ...
            ~isscalar(cfg.output.power_tolerance_dB) || ...
            ~isfinite(cfg.output.power_tolerance_dB) || ...
            cfg.output.power_tolerance_dB < 0
        error('JammingDataset:InvalidStructure', ...
            'cfg.output.power_tolerance_dB 必须是有限非负标量。');
    end
    powerTolerance_dB = double(cfg.output.power_tolerance_dB);
    if any(abs(bundle.target_target_power_dB(targetPresent) - ...
            bundle.target_measured_power_dB(targetPresent)) > ...
            powerTolerance_dB)
        error('JammingDataset:PowerMismatch', ...
            '真实目标的目标功率与实测功率不一致。');
    end

    for sampleIndex = 1:sampleCount
        ids = bundle.manifest.active_type_ids{sampleIndex};
        codes = bundle.manifest.active_type_codes{sampleIndex};
        componentCount = bundle.manifest.combination_size(sampleIndex);
        expectedLabel = false(1, numel(registry));
        expectedLabel(ids) = true;
        if ~isequal(logical(bundle.label_all(sampleIndex, :)), expectedLabel) || ...
                ~isequal(logical(bundle.label_selected(sampleIndex, :)), ...
                expectedLabel(enabledMask)) || ...
                ~isequal(logical(bundle.known_label(sampleIndex, :)), ...
                expectedLabel(knownMask))
            error('JammingDataset:LabelMismatch', ...
                '第 %d 行标签与 manifest 活动类型不一致。', sampleIndex);
        end
        unknownCount = sum(ismember(codes, cfg.types.unknown));
        if logical(bundle.unknown_present(sampleIndex)) ~= ...
                (unknownCount > 0) || ...
                bundle.unknown_component_count(sampleIndex) ~= unknownCount
            error('JammingDataset:OpenSetMismatch', ...
                '第 %d 行 known/unknown 标签不一致。', sampleIndex);
        end
        for fieldIndex = 1:numel(variableFields)
            if numel(bundle.(variableFields{fieldIndex}){sampleIndex}) ~= ...
                    componentCount
                error('JammingDataset:InvalidStructure', ...
                    '第 %d 行分量级字段长度与 combination_size 不一致。', ...
                    sampleIndex);
            end
        end
        if ~isequal(bundle.component_power_offset_dB{sampleIndex}, ...
                bundle.manifest.component_target_power_dB{sampleIndex}) || ...
                ~isequal(logical(bundle.weak_component_mask{sampleIndex}), ...
                logical(bundle.manifest.weak_component_mask{sampleIndex}))
            error('JammingDataset:ManifestMismatch', ...
                '第 %d 行功率偏置或弱分量掩码与 manifest 不一致。', sampleIndex);
        end
        targetPower = bundle.component_target_power_dB{sampleIndex};
        measuredPower = bundle.component_measured_power_dB{sampleIndex};
        if any(~isfinite(targetPower)) || any(~isfinite(measuredPower)) || ...
                any(abs(targetPower - measuredPower) > powerTolerance_dB)
            error('JammingDataset:PowerMismatch', ...
                '第 %d 行分量目标功率与实测功率不一致。', sampleIndex);
        end
        expectedRelative = targetPower - max(targetPower);
        if any(abs(bundle.relative_power_dB{sampleIndex} - ...
                expectedRelative) > powerTolerance_dB)
            error('JammingDataset:PowerMismatch', ...
                '第 %d 行最终相对功率不是由绝对目标功率计算。', sampleIndex);
        end
        inactiveOwners = ~ismember(schema.owner_code, codes);
        if any(bundle.parameter_mask(sampleIndex, inactiveOwners))
            error('JammingDataset:InvalidParameterTargets', ...
                '第 %d 行激活了非活动类型的参数 mask。', sampleIndex);
        end
    end

    if cfg.output.save_legacy
        if ~isfield(bundle, 'data_legacy') || ...
                ~isequal(bundle.data_legacy, ...
                [real(bundle.iq_complex), imag(bundle.iq_complex)])
            error('JammingDataset:LegacyMismatch', ...
                'data_legacy 必须严格等于 [real(iq),imag(iq)]。');
        end
    end
    validate_scenario(bundle.manifest, cfg, scenario);
end

function require_binary_matrix(value, expectedSize, name)
%REQUIRE_BINARY_MATRIX 校验逻辑或0/1矩阵及其精确形状。

    validValues = islogical(value) || ...
        (isnumeric(value) && isreal(value) && ...
        all(ismember(value(:), [0, 1])));
    if ~validValues || ~isequal(size(value), expectedSize)
        error('JammingDataset:InvalidStructure', ...
            '%s 必须是指定形状的 logical 或0/1矩阵。', name);
    end
end

function scenario = normalize_scenario(value)
%NORMALIZE_SCENARIO 规范场景文本并限制为三个公共入口。

    if isstring(value) && isscalar(value) && ~ismissing(value)
        scenario = char(value);
    elseif ischar(value) && isrow(value)
        scenario = value;
    else
        error('JammingDataset:UnknownScenario', 'scenario 必须是文本标量。');
    end
    scenario = lower(strtrim(scenario));
    if ~ismember(scenario, {'balanced', 'imbalanced', 'openset'})
        error('JammingDataset:UnknownScenario', ...
            'scenario 仅允许 balanced、imbalanced 或 openset。');
    end
end

function validate_scenario(manifest, cfg, scenario)
%VALIDATE_SCENARIO 检查 manifest 的不均衡标志和开放集划分约束。

    flags = vertcat(manifest.imbalance_flags{:});
    switch scenario
        case 'balanced'
            expected = logical([false, false, false]);
        case 'imbalanced'
            expected = logical([cfg.imbalance.component.enable, ...
                cfg.imbalance.combination.enable, ...
                cfg.imbalance.power.enable]);
        case 'openset'
            expected = logical([false, false, false]);
    end
    if ~isempty(flags) && ~all(flags == expected, 'all')
        error('JammingDataset:ScenarioMismatch', ...
            'manifest.imbalance_flags 与场景配置不一致。');
    end
    if strcmp(scenario, 'openset')
        splitNames = manifest.split;
        knownSplit = ismember(splitNames, {'train', 'calibration'});
        if any(manifest.unknown_present(knownSplit))
            error('JammingDataset:OpenSetMismatch', ...
                '开放集 train/calibration 划分不能含未知成分。');
        end
    end
end
