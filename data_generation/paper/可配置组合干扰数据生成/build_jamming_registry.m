function registry = build_jamming_registry(varargin)
%BUILD_JAMMING_REGISTRY 构建 v1 十类或 v2 十三类固定顺序注册表。
%   REGISTRY = BUILD_JAMMING_REGISTRY() 返回默认 v2 的 1×13 注册表。
%   REGISTRY = BUILD_JAMMING_REGISTRY(CFG) 根据 CFG 选择版本：缺少
%   cfg.registry 的历史配置按 v1 解释；cfg.registry.version=1 或 2 时按
%   显式版本构造。v2 只在稳定 ID 1--10 后追加 ID 11--13，旧顺序不变。
%   每项包含数值 ID、英文代码、中文名称、生成器函数句柄、参数名称和参数
%   单位。单位 dB、Hz、Hz/s、s、m、m/s 分别表示分贝、赫兹、赫兹每秒、
%   秒、米和米每秒；单位 1 表示计数、模式代码或无量纲比例。
%
%   修改示例：
%       registry = build_jamming_registry();
%       fmbNames = registry(1).parameter_names; % 读取 FMB 的参数列定义。
%   若新增参数，应同时在对应项的 parameter_names 和 parameter_units 末尾
%   添加名称与单位，并保持二者长度和顺序严格一致。

    if nargin > 1
        error('JammingRegistry:TooManyInputs', ...
            'build_jamming_registry 最多接受一个可选配置参数。');
    end
    registryVersion = resolve_registry_version(varargin{:});

    delayNames8 = arrayfun(@(index) sprintf('delay_%02d_s', index), ...
        1:8, 'UniformOutput', false);
    amplitudeNames8 = arrayfun(@(index) sprintf('amplitude_%02d', index), ...
        1:8, 'UniformOutput', false);
    delayNames4 = arrayfun(@(index) sprintf('delay_%02d_s', index), ...
        1:4, 'UniformOutput', false);
    rangeNames4 = arrayfun(@(index) sprintf('range_%02d_m', index), ...
        1:4, 'UniformOutput', false);
    amplitudeNames4 = arrayfun(@(index) sprintf('amplitude_%02d', index), ...
        1:4, 'UniformOutput', false);

    registry(1) = create_entry(1, 'FMB', '阻塞式噪声调频干扰', @generate_fmb, ...
        {'JNR_dB', 'bandwidth_factor', 'interference_bandwidth_Hz', ...
        'center_frequency_Hz', 'arrival_delay_s'}, ...
        {'dB', '1', 'Hz', 'Hz', 's'});

    registry(2) = create_entry(2, 'AMA', '噪声调幅干扰', @generate_ama, ...
        {'JNR_dB', 'bandwidth_factor', 'interference_bandwidth_Hz', ...
        'center_frequency_Hz', 'modulation_index', 'arrival_delay_s'}, ...
        {'dB', '1', 'Hz', 'Hz', '1', 's'});

    registry(3) = create_entry(3, 'SawFM', '锯齿波扫频干扰', @generate_sawfm, ...
        {'JNR_dB', 'sweep_bandwidth_Hz', 'sweep_slope_Hz_per_s', ...
        'sweep_period_s', 'arrival_delay_s'}, ...
        {'dB', 'Hz', 'Hz/s', 's', 's'});

    registry(4) = create_entry(4, 'SinFM', '正弦调频干扰', @generate_sinfm, ...
        {'JNR_dB', 'center_frequency_Hz', 'frequency_deviation_Hz', ...
        'modulation_frequency_Hz', 'modulation_period_s', 'arrival_delay_s'}, ...
        {'dB', 'Hz', 'Hz', 'Hz', 's', 's'});

    registry(5) = create_entry(5, 'SN', '智能噪声干扰', @generate_smart_noise, ...
        {'JNR_dB', 'sample_width_s', 'num_replicas', 'sample_period_s', ...
        'arrival_delay_s'}, ...
        {'dB', 's', '1', 's', 's'});

    % MFT/RangeFakeTarget 的 arrival_delay_s 字段保留接口和单位，但生成器
    % 将公共到达时延吸收到逐目标最终时延后返回 NaN，供编码层关闭该掩码。
    mftNames = [{'JNR_dB', 'num_targets', 'mean_delay_s', 'mean_spacing_s'}, ...
        delayNames8, amplitudeNames8, {'arrival_delay_s'}];
    mftUnits = [{'dB', '1', 's', 's'}, repmat({'s'}, 1, 8), ...
        repmat({'1'}, 1, 8), {'s'}];
    registry(6) = create_entry(6, 'MFT', '多假目标干扰', @generate_mft, ...
        mftNames, mftUnits);

    registry(7) = create_entry(7, 'VFT', '速度假目标干扰', @generate_vft, ...
        {'JNR_dB', 'doppler_Hz', 'velocity_mps', 'arrival_delay_s'}, ...
        {'dB', 'Hz', 'm/s', 's'});

    registry(8) = create_entry(8, 'ISRJ', '间歇采样转发干扰', @generate_isrj, ...
        {'JNR_dB', 'sample_width_s', 'num_replicas', 'sample_period_s', ...
        'arrival_delay_s', 'mode_code'}, ...
        {'dB', 's', '1', 's', 's', '1'});

    rangeFakeTargetNames = [{'JNR_dB', 'num_targets', 'mean_delay_s'}, ...
        delayNames4, rangeNames4, amplitudeNames4, {'arrival_delay_s'}];
    rangeFakeTargetUnits = [{'dB', '1', 's'}, repmat({'s'}, 1, 4), ...
        repmat({'m'}, 1, 4), repmat({'1'}, 1, 4), {'s'}];
    registry(9) = create_entry(9, 'RangeFakeTarget', '距离假目标干扰', ...
        @generate_range_fake_target, rangeFakeTargetNames, rangeFakeTargetUnits);

    % Traction 的 amplitude 是唯一全局幅度监督。组合层不得再为其独立
    % 采样 JNR 或执行绝对功率归一化；功率不均衡只作为线性幅度增益并入
    % 最终 effective amplitude。传播到达时延由 initial_range_m 及脉间
    % 距离/时延变化表达，因此此处不重复声明 JNR_dB 或 arrival_delay_s。
    registry(10) = create_entry(10, 'Traction', '拖引干扰', @generate_traction, ...
        {'initial_range_m', 'velocity_mps', 'amplitude', ...
        'range_change_per_pulse_m', 'delay_change_per_pulse_s'}, ...
        {'m', 'm/s', '1', 'm', 's'});

    if registryVersion == 1
        return;
    end

    names8 = @(prefix, suffix) arrayfun(@(index) sprintf( ...
        '%s_%02d%s', prefix, index, suffix), ...
        1:8, 'UniformOutput', false);
    names32 = @(prefix, suffix) arrayfun(@(index) sprintf( ...
        '%s_%02d%s', prefix, index, suffix), ...
        1:32, 'UniformOutput', false);

    combNames = [{'JNR_dB', 'num_teeth', 'spacing_Hz', ...
        'center_offset_Hz', 'amplitude_mode_code', 'arrival_delay_s'}, ...
        names8('frequency', '_Hz'), names8('amplitude', ''), ...
        names8('phase', '_rad')];
    combUnits = [{'dB', '1', 'Hz', 'Hz', '1', 's'}, ...
        repmat({'Hz'}, 1, 8), repmat({'1'}, 1, 8), ...
        repmat({'rad'}, 1, 8)];
    registry(11) = create_entry(11, 'CombSpectrum', '梳状谱干扰', ...
        @generate_comb_spectrum, combNames, combUnits);

    clutterNames = [{'JNR_dB', 'mode_code', 'total_pulse_count', ...
        'mean_width_s', 'duty_cycle', 'mean_amplitude', ...
        'minimum_frequency_Hz', 'maximum_frequency_Hz', ...
        'arrival_delay_s'}, names32('start', '_s'), ...
        names32('width', '_s'), names32('amplitude', ''), ...
        names32('frequency', '_Hz'), names32('phase', '_rad')];
    clutterUnits = [{'dB', '1', '1', 's', '1', '1', 'Hz', 'Hz', 's'}, ...
        repmat({'s'}, 1, 32), repmat({'s'}, 1, 32), ...
        repmat({'1'}, 1, 32), repmat({'Hz'}, 1, 32), ...
        repmat({'rad'}, 1, 32)];
    registry(12) = create_entry(12, 'ClutterPulse', '杂乱脉冲干扰', ...
        @generate_clutter_pulse, clutterNames, clutterUnits);

    smspNames = [{'JNR_dB', 'num_subpulses', 'subpulse_width_s', ...
        'chirp_rate_multiplier', 'subpulse_chirp_rate_Hz_per_s', ...
        'subpulse_bandwidth_Hz', 'output_duration_s', ...
        'arrival_delay_s', 'initial_phase_rad'}, ...
        names8('subpulse_start', '_s')];
    smspUnits = [{'dB', '1', 's', '1', 'Hz/s', 'Hz', 's', 's', 'rad'}, ...
        repmat({'s'}, 1, 8)];
    registry(13) = create_entry(13, 'SpectralDispersion', ...
        '频谱弥散干扰', @generate_spectral_dispersion, ...
        smspNames, smspUnits);

    expectedCounts = [30, 169, 17];
    for index = 11:13
        if numel(registry(index).parameter_names) ~= ...
                expectedCounts(index - 10) || ...
                numel(registry(index).parameter_names) ~= ...
                numel(registry(index).parameter_units)
            error('JammingRegistry:InvalidMetadata', ...
                '新增注册项的参数名、单位或固定列数不一致。');
        end
    end
end

function version = resolve_registry_version(varargin)
%RESOLVE_REGISTRY_VERSION 解析无参 v2、缺失版本 v1 或显式 1/2。

    if isempty(varargin)
        version = 2;
        return;
    end
    cfg = varargin{1};
    if ~isstruct(cfg) || ~isscalar(cfg)
        throw_invalid_version();
    end
    if ~isfield(cfg, 'registry')
        version = 1;
        return;
    end
    registryConfig = cfg.registry;
    valid = isstruct(registryConfig) && isscalar(registryConfig) && ...
        isfield(registryConfig, 'version') && ...
        isnumeric(registryConfig.version) && ...
        isreal(registryConfig.version) && isscalar(registryConfig.version) && ...
        isfinite(registryConfig.version) && ...
        registryConfig.version == fix(registryConfig.version) && ...
        ismember(double(registryConfig.version), [1, 2]);
    if ~valid
        throw_invalid_version();
    end
    version = double(registryConfig.version);
end

function throw_invalid_version()
%THROW_INVALID_VERSION 抛出稳定的注册表版本错误。

    error('JammingRegistry:InvalidVersion', ...
        'cfg.registry.version 必须是数值标量 1 或 2。');
end

function entry = create_entry(id, code, chineseName, generator, ...
        parameterNames, parameterUnits)
%CREATE_ENTRY 将一类干扰的元数据封装为标量注册项。
%   ID 为顺序编号；CODE 和 CHINESENAME 为英文代码和中文名称；GENERATOR
%   为生成器函数句柄；PARAMETERNAMES 与 PARAMETERUNITS 为等长单元数组。

    entry = struct( ...
        'id', id, ...
        'code', code, ...
        'chinese_name', chineseName, ...
        'generator', generator, ...
        'parameter_names', {parameterNames}, ...
        'parameter_units', {parameterUnits});
end
